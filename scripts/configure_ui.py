"""Generate public-only static UI configuration. Never put database URLs/secrets here."""
import argparse
import json
from pathlib import Path
from urllib.parse import urlsplit


def api_url(value):
    parsed = urlsplit(value)
    if parsed.scheme not in ('http', 'https') or not parsed.hostname or parsed.username or parsed.password or parsed.query or parsed.fragment:
        raise argparse.ArgumentTypeError('Expected a public HTTP(S) API base URL without credentials, query or fragment')
    try:
        parsed.port
    except ValueError as exc:
        raise argparse.ArgumentTypeError('Invalid API port') from exc
    return value.rstrip('/')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--restaurants-url', type=api_url, default='http://localhost:8001')
    parser.add_argument('--dining-url', type=api_url, default='http://localhost:8002')
    parser.add_argument('--output', type=Path, default=Path('ui/config.js'))
    args = parser.parse_args()
    config = {'restaurants': args.restaurants_url, 'dining': args.dining_url}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('// Public browser API endpoints only. Generated by scripts/configure_ui.py.\nwindow.PICKY_CONFIG = ' + json.dumps(config, indent=2) + ';\n')
    print(f'Generated public configuration: {args.output}')


if __name__ == '__main__':
    main()
